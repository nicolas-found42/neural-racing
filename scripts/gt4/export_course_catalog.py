#!/usr/bin/env python3
"""Join unchanged GT4 COURSE rows, localized SDB names and extracted RNW resources.

Never infer topology or section selection from resource names. Availability defaults
false until an independent source binding and geometry validation admit a resource.
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def strings(path):
    b = path.read_bytes()
    if b[:4] != b"GTST":
        raise ValueError("not a GTST string table")
    count, encoding = struct.unpack_from("<II", b, 4)
    if encoding != 1:
        raise ValueError("unsupported string-table endian")
    result = []
    for i in range(count):
        offset = 16 + count * 4 + struct.unpack_from("<I", b, 16 + i * 4)[0] + 2
        result.append(b[offset:b.index(0, offset)].decode("utf-8"))
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--decoded", type=Path, required=True)
    ap.add_argument("--specdb", type=Path, required=True)
    ap.add_argument("--courses", type=Path, required=True)
    ap.add_argument("--geometry-manifest", type=Path, help="published independently validated geometry IDs")
    ap.add_argument("--native-classification", action="store_true", help="apply recovered COURSE topology and RACE section-copy semantics")
    ap.add_argument("--bindings", type=Path, help="independently evidenced per-resource topology/section admission JSON")
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--report", type=Path, required=True)
    args = ap.parse_args()
    course_path = args.decoded / "COURSE.json"
    names_path = args.decoded / "COURSE_NAME_american.json"
    course = json.loads(course_path.read_text())
    names = json.loads(names_path.read_text())
    localized = strings(args.specdb / "american_StrDB.sdb")
    labels = {r["label"]: localized[struct.unpack("<I", bytes(r["bytes"]))[0]] for r in names["rows"]}
    rows = {r["label"]: r for r in course["rows"]}
    inventory = json.loads((args.courses / "course-inventory.json").read_text())["courses"]
    if set(rows) != {c["id"] for c in inventory}:
        raise ValueError("COURSE and extracted resource identities do not match")
    bindings = json.loads(args.bindings.read_text()) if args.bindings else {}
    geometry_manifest = json.loads(args.geometry_manifest.read_text()) if args.geometry_manifest else {}
    validated_ids = set(geometry_manifest.get("validated_ids", []))
    race_path = args.decoded / "RACE.json"
    races = json.loads(race_path.read_text())["rows"]
    events = {}
    for race in races:
        raw = bytes(race["bytes"])
        course_id = struct.unpack_from("<I", raw)[0]
        section = max(-1, struct.unpack_from("<b", raw, 0x89)[0])
        events.setdefault(course_id, []).append(dict(id=race["id"], label=race["label"], section=section))
    records, rust = [], ["// Generated by scripts/gt4/export_course_catalog.py; retain source IDs and native field values.", "&["]
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    for resource in inventory:
        ident = resource["id"]
        geometry = json.loads((args.courses / (ident + ".json")).read_text())
        row = rows[ident]
        raw = row["bytes"]
        binding = {}
        source_events = events.get(row["id"], [])
        if args.native_classification:
            binding = dict(topology={0:"Closed",1:"Open",2:"Area"}.get(raw[18], "Unknown"), evidence="COURSE+0x12 copied to conductorCBDE by0x34c7e0;0x34c5e0/ProcessGoalLine use1 for endpoint-controlled route;0x359008 skips lap tracking for2.")
            sections = {e["section"] for e in source_events}
            if len(sections) == 1 and next(iter(sections)) >= 0:
                binding["section"] = next(iter(sections))
                binding["topology"] = "Open"
                binding["evidence"] += " All original RACE events for this resource select one section;0x35e108 copies signedRACE+0x89 to packed+0x21,0x34d418 targetsconductorF818;SetupGlobalStatusPre selectsF839;0x395528/395588 selectRNWsectionstart/goal."
        if ident in validated_ids and binding.get("topology") in ("Closed", "Open", "Area"):
            binding["available"] = True
            binding["geometry_evidence"] = str(args.geometry_manifest)
        binding.update(bindings.get(ident, {}))
        topology = binding.get("topology", "Unknown")
        if topology not in ("Closed", "Open", "NonDriving", "Area", "Unknown"):
            raise ValueError("invalid evidenced topology")
        section = binding.get("section")
        if section is None:
            start, goal = geometry["runway"]["start_v"], geometry["runway"]["goal_v"]
        else:
            selected = geometry["sections"][section]
            start, goal = selected["start_v"], selected["goal_v"]
        available = binding.get("available", False)
        if available and (topology not in ("Closed", "Open", "Area") or not binding.get("evidence")):
            raise ValueError("available course requires explicit driving-topology evidence")
        condition = {0: "Dry", 1: "Wet", 2: "Dirt", 3: "Snow"}.get(raw[16], "Unknown")
        kind = binding.get("kind", {"Dry": "Road", "Wet": "Road", "Dirt": "Dirt", "Snow": "Snow"}.get(condition, "Unknown"))
        if topology == "Area" and "kind" not in binding:
            kind = "Unknown"
        if kind not in ("Road", "Dirt", "Snow", "License", "Photo", "Unknown"):
            raise ValueError("invalid course kind")
        aliases = binding.get("aliases", [])
        if aliases and not binding.get("evidence"):
            raise ValueError("identity aliases require evidence")
        record = dict(id=ident, course_id=row["id"], label=labels.get(ident, ident), label_source="COURSE_NAME_american" if ident in labels else "exact resource ID", condition=condition, source_topology=raw[18], topology=topology, section=section, start_v=start, goal_v=goal, available=available, binding=binding, source_sha256=resource["source_sha256"], native_sections=geometry["sections"], raw_course_bytes=raw, source_race_events=source_events)
        records.append(record)
        rust.append("    Gt4Course { id: %s, name: %s, slug: %s, topology: CourseTopology::%s, condition: CourseCondition::%s, source_topology: %d, section: %s, start_v: %sf32, goal_v: %sf32, kind: CourseKind::%s, available: %s, aliases: &[%s] }," % (quote(ident), quote(record["label"]), quote("gt4-"+ident), topology, condition, raw[18], "None" if section is None else "Some(%d)" % section, repr(start), repr(goal), kind, str(available).lower(), ", ".join(quote(a) for a in aliases)))
    rust.append("]")
    args.output.write_text("\n".join(rust)+"\n")
    report = dict(schema=1, geometry_manifest_sha256=sha(args.geometry_manifest) if args.geometry_manifest else None, sources={str(p):sha(p) for p in (course_path,names_path,race_path,args.specdb/"american_StrDB.sdb",args.specdb/"COURSE.dbt",args.specdb/"COURSE.idi")}, condition_evidence="Native 0x1b3030 switches COURSE+0x10 to canonical ELF strings 0x693280 dry,0x693288 wet,0x693290 dirt,0x693298 snow; native0x447f48 reads table0x22.", limitations=["Topology/section bindings use recovered native data flow when --native-classification is set; no resource-name rules. Availability still requires geometry validation.", "Localized COURSE_NAME table contains only23 labels; remaining labels preserve exact resource IDs.", "COURSE mapping NameEng is not used: its actual GT4 strings are attribute masks rather than human names."], courses=records)
    args.report.write_text(json.dumps(report,indent=2,ensure_ascii=False)+"\n")

if __name__ == "__main__":
    main()
